//! Writes the preload's compatibility stamp note (src/preload_stamp.rs in
//! the parent package) for src/lib.rs to emit as `.note.literoot.preload`:
//! the derived protocol_version and this build's flavour (traphost with
//! `inguest-trap`, else liteinst). Also writes the reporter-off marker
//! bytes, which only a reporter-off fixture links in.

#[path = "../src/preload_stamp.rs"]
mod preload_stamp;

use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set for build scripts"),
    );
    let root = manifest
        .parent()
        .expect("preload/ lives inside the literoot package")
        .to_path_buf();
    for rel in preload_stamp::STAMP_FILES {
        println!("cargo::rerun-if-changed={}", root.join(rel).display());
    }
    for rel in ["Cargo.lock", "preload/Cargo.lock", "src/preload_stamp.rs"] {
        println!("cargo::rerun-if-changed={}", root.join(rel).display());
    }
    println!("cargo::rerun-if-changed=build.rs");
    let protocol = preload_stamp::protocol_version(&root).unwrap_or_else(|e| {
        panic!("literoot-preload build: cannot derive the stamp protocol_version: {e}")
    });
    preload_stamp::check_lock_agreement(&root)
        .unwrap_or_else(|e| panic!("literoot-preload build: {e}"));
    let flavour = if std::env::var_os("CARGO_FEATURE_INGUEST_TRAP").is_some() {
        preload_stamp::FLAVOUR_TRAPHOST
    } else {
        preload_stamp::FLAVOUR_LITEINST
    };
    let note = preload_stamp::note_bytes(protocol, flavour);
    let marker = preload_stamp::REPORTER_OFF_MARKER;
    let generated = format!(
        "// Generated by preload/build.rs.\n\
         const LITEROOT_NOTE_BYTES: [u8; {}] = {:?};\n\
         #[allow(dead_code)] // linked in only by the reporter-off fixture\n\
         pub(crate) const REPORTER_OFF_MARKER: [u8; {}] = {:?};\n",
        note.len(),
        note,
        marker.len(),
        marker
    );
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR is set for build scripts"))
        .join("literoot_note.rs");
    std::fs::write(&out, generated)
        .unwrap_or_else(|e| panic!("literoot-preload build: write {}: {e}", out.display()));
}
